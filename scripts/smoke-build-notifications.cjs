'use strict';
// Real app and notifications; sandbox workers and preview are local test fixtures.
const { app, BrowserWindow, session } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const { randomUUID } = require('node:crypto');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'engelbart-build-notifications-'));
app.setPath('userData', path.join(root, 'electron'));
Object.assign(process.env, { ENGELBART_HOME_DIR: root, ENGELBART_SUMMARIES: 'off', ENGELBART_WEB_PDFS: 'off', ENGELBART_HEADLESS: '1', ENGELBART_BART_FAKE: '1' });
const workers = [];
// Permit only this fixture's loopback preview; production URL validation is unchanged.
let fixtureUrl;
const workerModule = require('../src/main/sandbox/worker.cjs'), safePreview = workerModule.safePreview;
workerModule.safePreview = url => url === fixtureUrl ? url : safePreview(url);
const manager = require('../src/main/sandbox/manager.cjs'), original = manager.createSandboxManager;
manager.createSandboxManager = options => original({ ...options, readEnv: () => ({}), launch(request, _env, emit) {
  if (['probe', 'kill'].includes(request.command)) return { done: Promise.resolve().then(() => emit({ event: 'result', state: request.command === 'probe' ? 'ready' : 'gone' })) };
  assert.equal(request.command, 'start');
  let finish;
  const done = new Promise(resolve => { finish = resolve; });
  const worker = { request, emit, done, stop: async () => { await emit({ event: 'stopped' }); finish(); } };
  workers.push(worker);
  return worker;
} });
require('../src/main/index.cjs');
const db = require('../src/main/store/db.cjs');
const projects = require('../src/main/store/projects.cjs');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
const js = (wc, code) => wc.executeJavaScript(code, true).catch(error => { console.error('Script:', code); throw error; });
async function until(check, name) {
  for (let i = 0; i < 160; i++) { const value = await check(); if (value) return value; await pause(75); }
  throw Error(`Timed out: ${name}`);
}
const click = (wc, selector) => js(wc, `document.querySelector(${JSON.stringify(selector)}).click()`);
const action = (wc, label) => js(wc, `(()=>{const button=[...document.querySelectorAll('.repo-details-footer button')].find(button=>button.textContent===${JSON.stringify(label)});if(!button||button.disabled)throw Error('Unavailable action: '+${JSON.stringify(label)});button.click()})()`);
const server = http.createServer((_req, res) => { res.setHeader('content-type', 'text/html'); res.end('<!doctype html><title>Finished preview</title><h1>Ready to use</h1>'); });
app.whenReady().then(async () => {
  let win;
  try {
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const url = `http://127.0.0.1:${server.address().port}/`;
    fixtureUrl = url;
    // Navigation remains a real GitHub URL in Stage, served by this isolated
    // browser partition's fixture rather than requesting the public website.
    await session.fromPartition('persist:browser').protocol.handle('https', () => new Response('<!doctype html><title>Repository on GitHub</title><h1>example/research-board</h1>', { headers: { 'Content-Type': 'text/html' } }));
    win = await until(() => BrowserWindow.getAllWindows()[0], 'window');
    win.setFocusable(false); win.setSize(1450, 940); win.showInactive();
    const wc = win.webContents;
    await until(() => js(wc, '!!window.engelbartAPI').catch(() => false), 'app bridge');
    const made = await js(wc, `window.engelbartAPI.createProjectWithWelcome({name:'Build notifications',directory:${JSON.stringify(root)}})`);
    const config = await js(wc, 'window.engelbartAPI.config()');
    const libraryDb = await db.openLibraryDb(config.dataRoot);
    const repo = await libraryDb.insert({ id: randomUUID(), name: 'example/research-board', type: 'website', tags: ['git'], url: 'https://github.com/example/research-board' });
    await projects.linkToWorkspace({ homeDir: root, root: config.home, dataRoot: config.dataRoot, libraryDb }, made.project.id, made.workspaceId, [repo.id]);
    wc.reload();
    const row = `[data-rail-row="${repo.id}"]`;
    await until(() => js(wc, '!!document.querySelector("[data-rail-section-toggle=GitHub]")').catch(() => false), 'repository section');
    await js(wc, `(()=>{const section=document.querySelector('[data-rail-section-toggle=GitHub]');if(section.getAttribute('aria-expanded')!=='true')section.click()})()`);
    await until(() => js(wc, `!!document.querySelector(${JSON.stringify(row)})`).catch(() => false), 'repo sidebar row');
    await until(() => workers.length, 'automatic build');
    await until(() => js(wc, '!!document.querySelector(".notification-badge")'), 'building notification');
    assert.equal(await js(wc, '[...document.querySelectorAll("button")].some(b=>b.textContent.trim()==="Repo")'), false, 'Repo tab removed');
    assert.equal(await js(wc, '!!document.querySelector(".repo-pane")'), false);
    assert.equal(await js(wc, 'document.querySelector("[data-stage] input").value'), '', 'build does not navigate');
    assert.equal(await js(wc, '!!document.querySelector("[data-repo-build], [data-repo-live]")'), false, 'sidebar has no Build or Live controls');
    await click(wc, '.notification-bell');
    await until(() => js(wc, 'document.querySelector("[data-build-status=starting] .notification-build")?.textContent==="Building…"'), 'building control');
    assert.equal(await js(wc, 'document.querySelector(".notification-panel").textContent.includes("Stop")'), false, 'Stop is inside details, not the notification row');
    await pause(180);
    fs.writeFileSync(path.join(root, 'building.png'), (await wc.capturePage()).toPNG());
    await click(wc, '.notification-repo');
    await until(() => win.contentView.children.some(view => view.webContents?.getURL() === repo.url), 'notification repo name opens GitHub in Stage');
    assert.notEqual(await js(wc, 'document.querySelector("[data-stage]").style.display'), 'none');
    assert.equal(workers.length, 1, 'navigation never starts another build');

    await click(wc, '.notification-bell');
    await click(wc, '.notification-build');
    await until(() => js(wc, '!!document.querySelector(".repo-details[open]")'), 'notification Building opens inspector');
    assert.equal(await js(wc, 'document.querySelector(".repo-details [data-tab=build]").getAttribute("aria-selected")'), 'true');
    assert.equal(await js(wc, 'document.querySelectorAll(".repo-details [role=tabpanel]:not([hidden])").length'), 1);
    await workers[0].emit({ event: 'progress', message: 'Installing dependencies — fixture output' });
    await click(wc, '.repo-details [data-tab=logs]');
    await until(() => js(wc, 'document.querySelector(".repo-details-log-pane:not([hidden])")?.textContent.includes("Installing dependencies — fixture output")'), 'detailed build output streams');
    await click(wc, '.repo-details [data-tab=environment]');
    await until(() => js(wc, '!!document.querySelector("[aria-label=\\"Environment variable name\\"]") && !document.querySelector(".environment-fields").disabled'), 'existing Environment view loads');
    await click(wc, '.repo-details [data-tab=build]');
    await pause(180);
    fs.writeFileSync(path.join(root, 'building-inspector.png'), (await wc.capturePage()).toPNG());
    await click(wc, '[aria-label="Close build details"]');
    await until(() => js(wc, '!document.querySelector(".repo-details[open]")'), 'close inspector');
    await click(wc, '.notification-bell');
    await click(wc, '.notification-dismiss');
    await workers[0].emit({ event: 'progress', message: 'Installing dependencies continues' });
    await pause(150);
    assert.equal(await js(wc, 'document.querySelectorAll(".notification-row").length'), 0, 'dismissed progress remains quiet');
    await click(wc, '[aria-label="Close notifications"]');
    await js(wc, '[...document.querySelectorAll("button")].find(b=>b.textContent.trim()==="Terminal").click()');
    await workers[0].emit({ event: 'sandbox_created', sandbox_id: 'fixture-sandbox' });
    await workers[0].emit({ event: 'ready', preview_url: url, port: server.address().port });
    await until(() => js(wc, '!!document.querySelector(".notification-badge")'), 'completion notification');
    assert.equal(await js(wc, 'document.querySelector("[data-stage]").style.display'), 'none', 'completion leaves Terminal selected');
    await click(wc, '.notification-bell');
    await until(() => js(wc, 'document.querySelector("[data-build-status=ready]")?.textContent.includes("Build finished")'), 'finished row');
    assert.equal(await js(wc, 'document.querySelectorAll(".notification-row").length'), 1, 'finished replaces building');
    assert.equal(await js(wc, '!!document.querySelector(".notification-build")'), false, 'finished notification has no separate Build button');
    assert.equal(await js(wc, 'document.querySelector(".notification-repo").getAttribute("href")'), repo.url);
    await pause(180);
    fs.writeFileSync(path.join(root, 'finished.png'), (await wc.capturePage()).toPNG());
    await click(wc, '.notification-description');
    await until(() => js(wc, '!!document.querySelector(".repo-details[open] .repo-toolbar-status-live")'), 'Build finished opens the existing live build inspector');
    assert.equal(await js(wc, '!!document.querySelector(".notification-panel")'), false, 'opening details closes the dropdown');
    assert.equal(workers.length, 1, 'Build finished never starts another build');
    await click(wc, '[aria-label="Close build details"]');
    await until(() => js(wc, 'document.activeElement===document.querySelector(".notification-bell")'), 'closing details restores focus to the bell');
    await click(wc, '.notification-bell');
    await click(wc, '.notification-open');
    await until(() => win.contentView.children.some(view => view.webContents?.getURL() === url), 'separate Open live opens Stage');
    assert.notEqual(await js(wc, 'document.querySelector("[data-stage]").style.display'), 'none');
    await js(wc, '[...document.querySelectorAll("button")].find(b=>b.textContent.trim()==="Terminal").click()');
    await click(wc, row);
    await until(() => js(wc, `document.querySelector("[data-stage]").style.display!=="none" && document.querySelector("[data-stage] input").value.includes("github.com/example/research-board")`), 'ready repo name still opens GitHub, not its preview');
    await workers[0].emit({ event: 'failed', error: 'Fixture build failed' });
    await click(wc, '.notification-bell');
    await until(() => js(wc, 'document.querySelector("[data-build-status=failed]")?.textContent.includes("Fixture build failed")'), 'failed build notification');
    assert.equal(await js(wc, '!!document.querySelector(".notification-build")'), false, 'failed notification has no separate Build button');
    await click(wc, '.notification-description');
    await until(() => js(wc, 'document.querySelector(".repo-details[open]")?.textContent.includes("Fixture build failed")'), 'Build failed opens existing inspector');
    await action(wc, 'Retry build');
    await until(() => workers.length === 2 && js(wc, '!!document.querySelector(".repo-toolbar-status-starting")'), 'Retry inside inspector starts a new build');
    await until(() => js(wc, '[...document.querySelectorAll(".repo-details-footer button")].some(b=>b.textContent==="Stop sandbox"&&!b.disabled)'), 'retry request finished');
    await action(wc, 'Stop sandbox');
    await until(() => js(wc, '!!document.querySelector(".repo-toolbar-status-inactive")'), 'Stop inside inspector stops the run');
    assert.equal(workers.length, 2, 'stopping never restarts a build');
    await action(wc, 'Retry build');
    await until(() => workers.length === 3, 'explicit restart from inspector');
    await workers[2].emit({ event: 'sandbox_created', sandbox_id: 'fixture-next' });
    await workers[2].emit({ event: 'ready', preview_url: url, port: server.address().port });
    await until(() => js(wc, '!!document.querySelector(".repo-toolbar-status-live")'), 'open inspector follows new run to live');
    await pause(180);
    fs.writeFileSync(path.join(root, 'ready-inspector.png'), (await wc.capturePage()).toPNG());
    await action(wc, 'Open preview');
    await until(() => js(wc, '!document.querySelector(".repo-details")'), 'opening preview closes the inspector');
    await click(wc, '.notification-bell');
    await until(() => js(wc, '!!document.querySelector("[data-build-status=ready]")'), 'latest build notification');
    await click(wc, '.notification-dismiss');
    wc.reload();
    await until(() => js(wc, '!!document.querySelector(".notification-bell")').catch(() => false), 'reloaded app');
    await click(wc, '.notification-bell');
    await until(() => js(wc, '!!document.querySelector(".notification-empty")'), 'dismissal survives reload');
    await js(wc, 'window.terminalAPI.bootstrap().then(s=>Promise.all(s.sessions.map(t=>window.terminalAPI.closeSession(t.id))))');
    console.log(JSON.stringify({ ok: true, root, checks: ['no Repo tab', 'sidebar and notification names open GitHub in Stage', 'separate Building inspector', 'streaming logs', 'Environment', 'completion replaces progress', 'no forced navigation', 'separate live-preview controls', 'retry and Stop inside inspector', 'sidebar has no Build or Live controls', 'explicit restart', 'dismissal persistence'] }));
    await libraryDb.close(); server.closeAllConnections(); server.close(); app.exit(0);
  } catch (error) {
    console.error(error); console.error('Artifacts:', root);
    if (win && !win.isDestroyed()) fs.writeFileSync(path.join(root, 'failure.png'), (await win.webContents.capturePage()).toPNG());
    server.closeAllConnections(); server.close(); app.exit(1);
  }
});
