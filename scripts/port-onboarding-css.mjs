// The import flow's styles (src/renderer/import/import-css.js) are the onboarding mockup's own CSS, scoped under `.ix`,
// so the app draws exactly what the mockup draws. Run again whenever the mockup's CSS changes:
//
//   node scripts/port-onboarding-css.mjs "<path to Onboarding.html>"
//
// What is dropped: the mockup's own controls (.dev toolbar, .restore, .editor panel) and its top bar (.top: the app has
// its own). Everything else is kept as written, with each selector put under `.ix` (`:root`, `html` and `body` become
// `.ix` itself, so the tokens and the base font apply to the flow and nothing outside it).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2];
if (!source) { console.error('usage: node scripts/port-onboarding-css.mjs <Onboarding.html>'); process.exit(1); }
const html = fs.readFileSync(source, 'utf8');
const css = html.slice(html.indexOf('<style>') + 7, html.indexOf('</style>')).replace(/\/\*[\s\S]*?\*\//g, '');

const DROP = /^\s*(\.dev|\.restore|\.editor|\.top\b|\.top\s|\.top\.|\.top \.pill)/;

function scopeSelector(selector) {
  const one = selector.trim();
  if (!one) return null;
  if (DROP.test(one)) return null;
  if (one === ':root' || one === 'html' || one === 'body' || one === 'html,body') return '.ix';
  if (one.startsWith('.editing')) return `.ix${one}`; // the flow's root carries .editing in the mockup's edit mode
  if (one.startsWith('*')) return `.ix ${one}`;
  return `.ix ${one}`;
}

// A small reader for flat CSS with @media blocks (the mockup has nothing deeper).
function rules(text) {
  const out = [];
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf('{', i);
    if (open < 0) break;
    const head = text.slice(i, open).trim();
    if (head.startsWith('@')) {
      let depth = 1, j = open + 1;
      while (j < text.length && depth) { if (text[j] === '{') depth += 1; else if (text[j] === '}') depth -= 1; j += 1; }
      out.push({ at: head, body: rules(text.slice(open + 1, j - 1)) });
      i = j;
    } else {
      const close = text.indexOf('}', open);
      out.push({ selector: head, body: text.slice(open + 1, close).trim() });
      i = close + 1;
    }
  }
  return out;
}

function write(list) {
  const parts = [];
  for (const rule of list) {
    if (rule.at) {
      const inner = write(rule.body);
      if (inner) parts.push(`${rule.at}{${inner}}`);
      continue;
    }
    const selectors = splitSelectors(rule.selector).map(scopeSelector).filter(Boolean);
    if (!selectors.length || !rule.body) continue;
    parts.push(`${[...new Set(selectors)].join(',')}{${rule.body}}`);
  }
  return parts.join('\n');
}

// Commas inside :is()/:not()/attribute values do not split a list.
function splitSelectors(text) {
  const out = [];
  let depth = 0, start = 0, quote = '';
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (quote) { if (c === quote) quote = ''; continue; }
    if (c === '"' || c === "'") quote = c;
    else if (c === '(' || c === '[') depth += 1;
    else if (c === ')' || c === ']') depth -= 1;
    else if (c === ',' && !depth) { out.push(text.slice(start, i)); start = i + 1; }
  }
  out.push(text.slice(start));
  return out;
}

const scoped = write(rules(css));
const target = path.join(root, 'src', 'renderer', 'import', 'import-css.js');
fs.writeFileSync(target, `// Generated by scripts/port-onboarding-css.mjs from the onboarding mockup (Onboarding.html): its CSS, scoped under .ix.\n// Edit the mockup and run the script again rather than editing this file; overrides of the app's own go in import-extra-css.js.\nexport const IMPORT_CSS = ${JSON.stringify(scoped)};\n`);
console.log(`wrote ${path.relative(root, target)} (${scoped.length} characters)`);
