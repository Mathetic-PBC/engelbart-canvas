'use strict';

// Generates Sources/EngelbartConnect/Texts.generated.swift from the Electron sources, so every prompt, skill and script
// the agents are handed is the reference implementation's text byte for byte (a retyped prompt drifts).
//   node mac/Packages/Connect/scripts/gen-texts.cjs
// Run it from the repository root after a prompt changes in src/. Only constant strings (and objects of strings) are
// taken; the functions that build texts from them are ported by hand in the Swift files that use them.

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '../../../..');
const req = (rel) => require(path.join(root, rel));

// [module, export name, Swift name]
const TAKE = [
  ['src/main/connect/skills.cjs', 'SKILLS', 'skills'],
  ['src/main/connect/apple-notes.cjs', 'SCRIPT', 'appleNotesScript'],
  ['src/main/connect/apple-notes.cjs', 'NOT_ALLOWED', 'appleNotesNotAllowed'],
];

// Script builders called with markers the Swift side replaces: __LIMIT__ (a number) and "__ID__" (a JSON string).
const TEMPLATES = [
  ['src/main/connect/web-chats.cjs', 'CHATGPT_LIST', 'chatgptList', ['__LIMIT__']],
  ['src/main/connect/web-chats.cjs', 'CLAUDE_LIST', 'claudeList', ['__LIMIT__']],
  ['src/main/connect/web-chats.cjs', 'CHATGPT_ONE', 'chatgptOne', ['__ID__']],
  ['src/main/connect/web-chats.cjs', 'CLAUDE_ONE', 'claudeOne', ['__ID__']],
  ['src/main/connect/web-chats.cjs', 'CHATGPT_DELETE', 'chatgptDelete', ['__ID__']],
  ['src/main/connect/web-chats.cjs', 'CLAUDE_DELETE', 'claudeDelete', ['__ID__']],
  ['src/main/connect/gmail.cjs', 'SEARCH_SCRIPT', 'gmailSearchScript', ['__LIMIT__']],
];
TAKE.push(['src/main/connect/gmail.cjs', 'ACCOUNT_SCRIPT', 'gmailAccountScript']);
TAKE.push(['src/main/onboarding/assistant-projects.cjs', 'SIGNED_IN', 'assistantSignedIn']);
TAKE.push(['src/main/onboarding/assistant-projects.cjs', 'FIND_COMPOSER', 'findComposer']);
TAKE.push(['src/main/onboarding/assistant-projects.cjs', 'NEW_CHAT', 'assistantNewChat']);
TAKE.push(['src/main/connect/web-signin.cjs', 'SIGN_IN_PAGES', 'signInPages']);
// browser.cjs scripts: numbers 111111 (offset) / 333333 (offset + max) / 4242 (scroll), "__REF__", "__TEXT__".
TEMPLATES.push(
  ['src/main/connect/browser.cjs', 'READ_SCRIPT', 'browserReadScript', [111111, 222222]],
  ['src/main/connect/browser.cjs', 'INFO_SCRIPT', 'browserInfoFocused', [null, false]],
  ['src/main/connect/browser.cjs', 'INFO_SCRIPT', 'browserInfoRef', ['__REF__', false]],
  ['src/main/connect/browser.cjs', 'INFO_SCRIPT', 'browserInfoSpot', ['__REF__', true]],
);
TEMPLATES.push(['src/main/onboarding/prompts.cjs', 'assistantProjectsPrompt', 'assistantProjectsPromptTemplate', ['__TODAY__']]);
// JSON blobs parsed at run time: the import tools' definitions and who gets which.
const JSONS = [
  ['src/main/connect/tools.cjs', 'IMPORT_TOOLS', 'importToolsJSON'],
  ['src/main/connect/tools.cjs', 'TOOLS_FOR', 'toolsForJSON'],
];

// Every constant string export of these modules, under its own name (camelCased).
const ALL_OF = [
  'src/main/connect/prompts.cjs',
  'src/main/onboarding/prompts.cjs',
];

const camel = (name) => name.toLowerCase().replace(/_([a-z0-9])/g, (_m, c) => c.toUpperCase());

function swiftString(text) {
  let out = '"';
  for (const ch of String(text)) {
    const code = ch.codePointAt(0);
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else if (code < 0x20 || code === 0x7f) out += `\\u{${code.toString(16)}}`;
    else out += ch;
  }
  return `${out}"`;
}

const lines = [
  '// GENERATED by mac/Packages/Connect/scripts/gen-texts.cjs from the Electron sources. Do not edit by hand.',
  '// swiftlint:disable all',
  '',
  'public enum Texts {',
];
const seen = new Set();
const emit = (swiftName, value, from) => {
  if (seen.has(swiftName)) return;
  seen.add(swiftName);
  lines.push(`    /// ${from}`);
  if (typeof value === 'string') {
    lines.push(`    public static let ${swiftName} = ${swiftString(value)}`);
  } else if (value && typeof value === 'object' && !Array.isArray(value) && Object.values(value).every((v) => typeof v === 'string')) {
    lines.push(`    public static let ${swiftName}: [String: String] = [`);
    for (const [k, v] of Object.entries(value)) lines.push(`        ${swiftString(k)}: ${swiftString(v)},`);
    lines.push('    ]');
    lines.push(`    public static let ${swiftName}Order: [String] = [${Object.keys(value).map(swiftString).join(', ')}]`);
  } else if (Array.isArray(value) && value.every((v) => typeof v === 'string')) {
    lines.push(`    public static let ${swiftName}: [String] = [${value.map(swiftString).join(', ')}]`);
  }
};

for (const [rel, name, swiftName] of TAKE) emit(swiftName, req(rel)[name], `${rel} ${name}`);
for (const [rel, name, swiftName, args] of TEMPLATES) {
  const value = req(rel)[name](...args);
  // `limit` arrives as a string marker: JS printed it bare, as a number would be.
  emit(swiftName, value, `${rel} ${name}(${args.join(', ')})`);
}
for (const [rel, name, swiftName] of JSONS) emit(swiftName, JSON.stringify(req(rel)[name]), `${rel} ${name} (JSON)`);
{
  const b = req('src/main/connect/browser.cjs');
  // TYPE_SCRIPT and SCROLL_SCRIPT are not exported: rebuilt from the module's source text.
  const src = fs.readFileSync(path.join(root, 'src/main/connect/browser.cjs'), 'utf8');
  const grab = (name) => { const m = src.match(new RegExp(`const ${name} = \\(([^)]*)\\) => \`([\\s\\S]*?)\`;`)); return m ? new Function(...m[1].split(',').map((x) => x.trim()), `return \`${m[2]}\`;`) : null; };
  const TYPE = grab('TYPE_SCRIPT'), SCROLL = grab('SCROLL_SCRIPT');
  emit('browserTypeReplace', TYPE('__REF__', '__TEXT__', true), 'browser.cjs TYPE_SCRIPT(ref, text, true)');
  emit('browserTypeAppend', TYPE('__REF__', '__TEXT__', false), 'browser.cjs TYPE_SCRIPT(ref, text, false)');
  emit('browserScrollRef', SCROLL('__REF__', 4242), 'browser.cjs SCROLL_SCRIPT(ref, dy)');
  emit('browserScrollPage', SCROLL('', 4242), 'browser.cjs SCROLL_SCRIPT("", dy)');
  emit('browserKeys', [...b.KEYS], 'browser.cjs KEYS');
}
for (const rel of ALL_OF) {
  const mod = req(rel);
  for (const [name, value] of Object.entries(mod)) {
    if (typeof value === 'function') continue;
    const prefix = rel.includes('onboarding') ? 'onboarding' : '';
    const swiftName = prefix ? prefix + camel(name).replace(/^./, (c) => c.toUpperCase()) : camel(name);
    emit(swiftName, value, `${rel} ${name}`);
  }
}
lines.push('}', '');
const out = path.join(__dirname, '../Sources/EngelbartConnect/Texts.generated.swift');
fs.writeFileSync(out, lines.join('\n'));
process.stdout.write(`wrote ${out} (${seen.size} texts)\n`);
